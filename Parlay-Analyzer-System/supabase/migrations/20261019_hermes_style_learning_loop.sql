CREATE OR REPLACE FUNCTION public.activate_ai_learning_proposal(p_proposal_id uuid)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  proposal_row public.ai_learning_prompt_proposals%ROWTYPE;
  active_version uuid;
BEGIN
  SELECT * INTO proposal_row
  FROM public.ai_learning_prompt_proposals
  WHERE id = p_proposal_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Learning proposal not found';
  END IF;
  IF proposal_row.status <> 'backtested'
     OR COALESCE((proposal_row.backtest->>'eligible')::boolean, false) IS NOT TRUE THEN
    RAISE EXCEPTION 'Proposal has not passed the validation backtest';
  END IF;
  IF proposal_row.candidate_version_id IS NULL THEN
    RAISE EXCEPTION 'Proposal has no candidate prompt version';
  END IF;

  SELECT id INTO active_version
  FROM public.ai_learning_prompt_versions
  WHERE is_active
  FOR UPDATE;

  IF active_version IS DISTINCT FROM proposal_row.base_version_id THEN
    RAISE EXCEPTION 'Active prompt changed after this proposal was generated; create a fresh proposal';
  END IF;

  UPDATE public.ai_learning_prompt_versions SET is_active = false WHERE is_active;
  UPDATE public.ai_learning_prompt_versions
  SET is_active = true, activated_at = now()
  WHERE id = proposal_row.candidate_version_id;
  UPDATE public.ai_learning_prompt_proposals
  SET status = 'approved', reviewed_at = now(), updated_at = now()
  WHERE id = p_proposal_id;

  INSERT INTO public.ai_learning_prompt_events(action, from_version_id, to_version_id, proposal_id, backtest)
  VALUES ('promote', active_version, proposal_row.candidate_version_id, p_proposal_id, proposal_row.backtest);

  RETURN jsonb_build_object('ok', true, 'versionId', proposal_row.candidate_version_id);
END;
$$;

CREATE OR REPLACE FUNCTION public.rollback_ai_learning_prompt_version(p_target_version_id uuid)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  active_version uuid;
  target_version_number bigint;
BEGIN
  SELECT version_number INTO target_version_number
  FROM public.ai_learning_prompt_versions
  WHERE id = p_target_version_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Target prompt version not found';
  END IF;

  IF target_version_number <> 1 AND NOT EXISTS (
    SELECT 1
    FROM public.ai_learning_prompt_events
    WHERE to_version_id = p_target_version_id
      AND action IN ('promote', 'rollback')
  ) THEN
    RAISE EXCEPTION 'Only the baseline or a previously activated version can be restored';
  END IF;

  SELECT id INTO active_version
  FROM public.ai_learning_prompt_versions
  WHERE is_active
  FOR UPDATE;

  IF active_version IS NOT DISTINCT FROM p_target_version_id THEN
    RETURN jsonb_build_object('ok', true, 'versionId', p_target_version_id, 'unchanged', true);
  END IF;

  UPDATE public.ai_learning_prompt_versions SET is_active = false WHERE is_active;
  UPDATE public.ai_learning_prompt_versions
  SET is_active = true, activated_at = now()
  WHERE id = p_target_version_id;

  INSERT INTO public.ai_learning_prompt_events(action, from_version_id, to_version_id)
  VALUES ('rollback', active_version, p_target_version_id);

  RETURN jsonb_build_object('ok', true, 'versionId', p_target_version_id);
END;
$$;

REVOKE ALL ON FUNCTION public.activate_ai_learning_proposal(uuid) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.rollback_ai_learning_prompt_version(uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.activate_ai_learning_proposal(uuid) TO service_role;
GRANT EXECUTE ON FUNCTION public.rollback_ai_learning_prompt_version(uuid) TO service_role;
