-- Auditable, bounded self-learning for Gemini's prediction policy.
-- No existing prediction, settlement, lesson, or prompt configuration is changed.

CREATE TABLE IF NOT EXISTS public.prediction_learning_evaluations (
  prediction_id text PRIMARY KEY,
  fixture_id integer NOT NULL,
  analysis_at timestamptz,
  settled_at timestamptz,
  league text,
  market_bet text,
  outcome text NOT NULL CHECK (outcome IN ('WIN', 'LOSS', 'HALF_WIN', 'HALF_LOSS', 'PUSH')),
  home_score integer,
  away_score integer,
  odds numeric,
  probability numeric,
  confidence numeric,
  ev_percent numeric,
  prediction_text text,
  input_snapshot jsonb NOT NULL DEFAULT '{}'::jsonb,
  classification_status text NOT NULL DEFAULT 'pending'
    CHECK (classification_status IN ('pending', 'classified', 'failed')),
  error_category text,
  classification jsonb NOT NULL DEFAULT '{}'::jsonb,
  classification_provider text,
  classification_model text,
  classification_updated_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_prediction_learning_evaluations_status
  ON public.prediction_learning_evaluations(classification_status, analysis_at);
CREATE INDEX IF NOT EXISTS idx_prediction_learning_evaluations_market
  ON public.prediction_learning_evaluations(market_bet, analysis_at);
CREATE INDEX IF NOT EXISTS idx_prediction_learning_evaluations_fixture
  ON public.prediction_learning_evaluations(fixture_id);

CREATE TABLE IF NOT EXISTS public.ai_learning_prompt_versions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  version_number bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  policy jsonb NOT NULL DEFAULT
    '{"minConfidence":6.5,"minEvPercent":0,"excludedMarketFamilies":[]}'::jsonb,
  prompt_addendum text NOT NULL DEFAULT '',
  source_proposal_id uuid,
  is_active boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  activated_at timestamptz
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_ai_learning_prompt_versions_single_active
  ON public.ai_learning_prompt_versions(is_active)
  WHERE is_active;

CREATE TABLE IF NOT EXISTS public.ai_learning_prompt_proposals (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  base_version_id uuid NOT NULL REFERENCES public.ai_learning_prompt_versions(id),
  candidate_version_id uuid REFERENCES public.ai_learning_prompt_versions(id),
  title text NOT NULL,
  rationale text NOT NULL,
  evidence_summary jsonb NOT NULL DEFAULT '{}'::jsonb,
  training_cutoff timestamptz NOT NULL,
  training_sample_size integer NOT NULL DEFAULT 0,
  validation_sample_size integer NOT NULL DEFAULT 0,
  baseline_policy jsonb NOT NULL,
  candidate_policy jsonb NOT NULL,
  training_metrics jsonb NOT NULL DEFAULT '{}'::jsonb,
  backtest jsonb,
  status text NOT NULL DEFAULT 'draft'
    CHECK (status IN ('draft', 'backtested', 'approved', 'rejected', 'insufficient_data')),
  provider text,
  model text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  reviewed_at timestamptz
);

CREATE INDEX IF NOT EXISTS idx_ai_learning_prompt_proposals_created
  ON public.ai_learning_prompt_proposals(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_ai_learning_prompt_proposals_status
  ON public.ai_learning_prompt_proposals(status, created_at DESC);

CREATE TABLE IF NOT EXISTS public.ai_learning_prompt_events (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  action text NOT NULL CHECK (action IN ('promote', 'rollback')),
  from_version_id uuid REFERENCES public.ai_learning_prompt_versions(id),
  to_version_id uuid NOT NULL REFERENCES public.ai_learning_prompt_versions(id),
  proposal_id uuid REFERENCES public.ai_learning_prompt_proposals(id),
  backtest jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_ai_learning_prompt_events_created
  ON public.ai_learning_prompt_events(created_at DESC);

ALTER TABLE public.prediction_learning_evaluations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ai_learning_prompt_versions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ai_learning_prompt_proposals ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ai_learning_prompt_events ENABLE ROW LEVEL SECURITY;

GRANT SELECT, INSERT, UPDATE, DELETE ON public.prediction_learning_evaluations TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.ai_learning_prompt_versions TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.ai_learning_prompt_proposals TO service_role;
